import { useMutation, useQueryClient } from "@tanstack/react-query";
import type { Session } from "@/lib/types";
import { api } from "@/lib/api";
import { useLlmStatus } from "@/lib/useLlmStatus";
import { fullTimestamp, humanizeTime } from "@/lib/utils";
import { Button } from "./ui/button";
import { Markdown } from "./Markdown";
import { useToast } from "./ui/toast";

interface SessionSummaryCardProps {
  session: Session;
}

export function SessionSummaryCard({ session }: SessionSummaryCardProps) {
  const { enabled } = useLlmStatus();
  const queryClient = useQueryClient();
  const { toast } = useToast();

  const mutation = useMutation({
    mutationFn: () => api.generateSummary(session.id),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["session", session.id] });
    },
    onError: (err: Error) => {
      toast(`Failed to generate summary: ${err.message}`, "error");
    },
  });

  // Render nothing when server-side LLM features are off.
  if (!enabled) return null;

  const summary = session.summary;

  return (
    <div className="rounded-xl border border-border bg-card p-5">
      <div className="flex items-center justify-between gap-3">
        <h2 className="text-sm font-semibold text-foreground">Summary</h2>
        <Button
          size="sm"
          variant="outline"
          onClick={() => mutation.mutate()}
          disabled={mutation.isPending}
        >
          {mutation.isPending
            ? "Generating…"
            : summary == null
              ? "Generate"
              : "Regenerate"}
        </Button>
      </div>

      {mutation.isPending ? (
        <div
          className="mt-3 flex items-center gap-2 text-xs text-muted-foreground"
          role="status"
          aria-live="polite"
        >
          <span
            aria-hidden="true"
            className="h-4 w-4 animate-spin rounded-full border-2 border-border border-t-primary"
          />
          Generating summary…
        </div>
      ) : summary == null ? (
        <p className="mt-3 text-xs text-muted-foreground">
          No summary yet. Generate one to capture intent, invariants, and a
          recap.
        </p>
      ) : (
        <div className="mt-3 space-y-4">
          <div>
            <div className="mb-1 text-[0.7rem] font-medium uppercase tracking-wide text-muted-foreground">
              Intent
            </div>
            <p className="text-sm text-foreground">{summary.intent}</p>
          </div>

          {summary.invariants.length > 0 && (
            <div>
              <div className="mb-1 text-[0.7rem] font-medium uppercase tracking-wide text-muted-foreground">
                Invariants
              </div>
              <ul className="list-disc space-y-1 pl-5 text-sm text-foreground">
                {summary.invariants.map((inv, i) => (
                  <li key={i}>{inv}</li>
                ))}
              </ul>
            </div>
          )}

          <div>
            <div className="mb-1 text-[0.7rem] font-medium uppercase tracking-wide text-muted-foreground">
              Summary
            </div>
            <Markdown>{summary.summary}</Markdown>
          </div>

          <div className="text-xs text-muted-foreground">
            generated by {summary.generated_by ?? "—"} ·{" "}
            <span title={fullTimestamp(summary.generated_at)}>
              {humanizeTime(summary.generated_at)}
            </span>{" "}
            · {summary.model}
          </div>
        </div>
      )}
    </div>
  );
}
