import { describe, expect, it } from "vitest";
import type { Message } from "./types";
import { classifyCommandMessage } from "./commandMessages";

function msg(partial: Partial<Message> & Pick<Message, "blocks">): Message {
  return {
    uuid: Math.random().toString(36).slice(2),
    parent_uuid: null,
    role: "user",
    kind: "text",
    model: null,
    is_sidechain: false,
    timestamp: null,
    text: "",
    usage: null,
    ...partial,
  };
}

describe("classifyCommandMessage", () => {
  it("labels a caveat message as command context", () => {
    const m = msg({
      blocks: [
        {
          type: "text",
          text: "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond ...</local-command-caveat>",
        },
      ],
    });
    const info = classifyCommandMessage(m);
    expect(info?.label).toBe("⌘ command context");
    expect(info?.raw).toContain("Caveat:");
  });

  it("labels a slash-command invocation with its name", () => {
    const m = msg({
      blocks: [
        {
          type: "text",
          text: "<command-name>/clear</command-name> <command-message>clear</command-message> <command-args></command-args>",
        },
      ],
    });
    expect(classifyCommandMessage(m)?.label).toBe("⌘ /clear");
  });

  it("appends non-empty command args to the label", () => {
    const m = msg({
      blocks: [
        {
          type: "text",
          text: "<command-name>/compact</command-name> <command-args>keep summary</command-args>",
        },
      ],
    });
    expect(classifyCommandMessage(m)?.label).toBe("⌘ /compact keep summary");
  });

  it("labels a command-output wrapper as command output", () => {
    const m = msg({
      blocks: [
        {
          type: "text",
          text: "<local-command-stdout>some output here</local-command-stdout>",
        },
      ],
    });
    expect(classifyCommandMessage(m)?.label).toBe("⌘ command output");
  });

  it("returns null for a normal user prose message", () => {
    const m = msg({ blocks: [{ type: "text", text: "Please fix the bug." }] });
    expect(classifyCommandMessage(m)).toBeNull();
  });

  it("returns null for an assistant message", () => {
    const m = msg({
      role: "assistant",
      blocks: [{ type: "text", text: "<command-name>/clear</command-name>" }],
    });
    expect(classifyCommandMessage(m)).toBeNull();
  });

  it("returns null for a tool_result message", () => {
    const m = msg({
      kind: "tool_result",
      blocks: [{ type: "tool_result", tool_use_id: "a", content: "x" }],
    });
    expect(classifyCommandMessage(m)).toBeNull();
  });
});
