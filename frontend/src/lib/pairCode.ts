/** The words both sides derive from the two hosts' public keys. Six words
 * (48 bits): grinding a colliding substitute host key stays out of reach of
 * a targeted relay attacker, while remaining readable over any human
 * channel. */
export async function pairCode(
  hostKeyA: string,
  hostKeyB: string,
): Promise<string> {
  // Order-independent: both sides sort, so either may derive it.
  const [x, y] = [hostKeyA, hostKeyB].map((k) => k.trim()).sort();
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(`conversations-pair-code/v1\n${x}\n${y}`),
  );
  const bytes = new Uint8Array(digest);
  return [0, 1, 2, 3, 4, 5].map((i) => WORDS[bytes[i]]).join(" ");
}
